#!/usr/bin/env python3
"""Generate optional hooks to census a candidate WWE 2K15 XDK D3D code window.

The default window is only an initial hypothesis. It includes the registered function
that calls VdSwap; the generated CSV helps discover which nearby functions are device,
state, resource, and draw operations while the game is running.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path


HEADER = r'''// Generated by tools/gen_d3d_census.py. Do not edit manually.
#include <atomic>
#include <chrono>
#include <cstddef>
#include <cstdint>
#include <cstdio>
#include <filesystem>
#include <fstream>
#include <thread>

#include <rex/filesystem.h>
#include <rex/ppc/context.h>
#include <rex/ppc/func.h>

namespace {

struct Entry {
  uint32_t address = 0;
  std::atomic<uint64_t> calls{0};
  std::atomic<uint32_t> r3{0}, r4{0}, r5{0}, r6{0};
  std::atomic<uint32_t> r7{0}, r8{0}, r9{0}, r10{0};
  uint64_t last_calls = 0;
};

Entry g_entries[{count}];

void Record(size_t index, const PPCContext& ctx) {
  Entry& entry = g_entries[index];
  entry.r3.store(ctx.r3.u32, std::memory_order_relaxed);
  entry.r4.store(ctx.r4.u32, std::memory_order_relaxed);
  entry.r5.store(ctx.r5.u32, std::memory_order_relaxed);
  entry.r6.store(ctx.r6.u32, std::memory_order_relaxed);
  entry.r7.store(ctx.r7.u32, std::memory_order_relaxed);
  entry.r8.store(ctx.r8.u32, std::memory_order_relaxed);
  entry.r9.store(ctx.r9.u32, std::memory_order_relaxed);
  entry.r10.store(ctx.r10.u32, std::memory_order_relaxed);
  entry.calls.fetch_add(1, std::memory_order_relaxed);
}

void DumpLoop() {
  const std::filesystem::path output =
      rex::filesystem::GetExecutableFolder() / "wwe2k15_d3d_census.csv";
  std::filesystem::path temporary = output;
  temporary += ".tmp";
  for (;;) {
    std::ofstream file(temporary, std::ios::trunc);
    if (file) {
      file << "address,total_calls,calls_last_2s,r3,r4,r5,r6,r7,r8,r9,r10\n";
      for (Entry& entry : g_entries) {
        const uint64_t calls = entry.calls.load(std::memory_order_relaxed);
        if (!calls) continue;
        file << std::hex << std::uppercase << entry.address << std::dec << ',' << calls << ','
             << calls - entry.last_calls << ',' << std::hex << std::uppercase
             << entry.r3.load(std::memory_order_relaxed) << ','
             << entry.r4.load(std::memory_order_relaxed) << ','
             << entry.r5.load(std::memory_order_relaxed) << ','
             << entry.r6.load(std::memory_order_relaxed) << ','
             << entry.r7.load(std::memory_order_relaxed) << ','
             << entry.r8.load(std::memory_order_relaxed) << ','
             << entry.r9.load(std::memory_order_relaxed) << ','
             << entry.r10.load(std::memory_order_relaxed) << '\n';
        entry.last_calls = calls;
      }
      file.close();
      std::error_code ec;
      std::filesystem::remove(output, ec);
      ec.clear();
      std::filesystem::rename(temporary, output, ec);
    }
    std::this_thread::sleep_for(std::chrono::seconds(2));
  }
}

struct Starter {
  Starter() {
{init}
    std::thread(DumpLoop).detach();
  }
} g_starter;

}  // namespace

'''


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--register", required=True, type=Path)
    parser.add_argument("--out", required=True, type=Path)
    parser.add_argument("--lo", type=lambda value: int(value, 0), default=0x82BA0000)
    parser.add_argument("--hi", type=lambda value: int(value, 0), default=0x82BB0000)
    args = parser.parse_args()
    if args.lo >= args.hi:
        parser.error("--lo must be lower than --hi")

    register_text = args.register.read_text(encoding="utf-8", errors="replace")
    addresses = sorted(
        int(address, 16)
        for address in re.findall(r"SetFunction\(0x([0-9A-Fa-f]+),\s*sub_", register_text)
        if args.lo <= int(address, 16) < args.hi
    )
    if not addresses:
        parser.error("no registered game functions found in the selected address window")
    if len(addresses) > 2048:
        parser.error(f"window selected {len(addresses)} functions; narrow it to avoid excessive hooks")

    init = "\n".join(
        f"    g_entries[{index}].address = 0x{address:08X};" for index, address in enumerate(addresses)
    )
    hooks = []
    for index, address in enumerate(addresses):
        name = f"sub_{address:08X}"
        hooks.append(
            f"REX_EXTERN(__imp__{name});\n"
            f"extern \"C\" REX_FUNC({name}) {{\n"
            f"  Record({index}, ctx);\n"
            f"  __imp__{name}(ctx, base);\n"
            f"}}\n"
        )

    args.out.parent.mkdir(parents=True, exist_ok=True)
    source = HEADER.replace("{count}", str(len(addresses))).replace("{init}", init)
    args.out.write_text(source + "\n".join(hooks), encoding="utf-8")
    print(f"Generated {len(addresses)} census hooks for 0x{args.lo:08X}-0x{args.hi:08X}: {args.out}")


if __name__ == "__main__":
    main()
